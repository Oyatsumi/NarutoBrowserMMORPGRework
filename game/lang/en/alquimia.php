if (function_exists('doquery')) {
    // Receitas com o mesmo nome de um item/drop usam a tradução do item (não sobrescreve as listas de conteúdo).
    $q = doquery("SELECT r.nome,r.nome_en FROM {{table}} r WHERE r.nome NOT IN (SELECT name FROM ".$GLOBALS["dbsettings"]["prefix"]."_items) AND r.nome NOT IN (SELECT name FROM ".$GLOBALS["dbsettings"]["prefix"]."_drops)", "receitas");
    while ($q && $r = mysqli_fetch_array($q)) {
        if (trim((string)$r["nome_en"]) == "") { continue; }
        $alq[html_entity_decode(stripslashes($r["nome"]), ENT_QUOTES, "UTF-8")] = $r["nome_en"];
        if (!isset($alq[$r["nome"]])) { $alq[$r["nome"]] = $r["nome_en"]; }
    }
}
return $alq;
